package enity;

public class User {
    private String userName;
    private String userEmail;
    private int userAge;
    private int userID;

    public User (String userName, String userEmail, int userAge, int userID){
        this.userName = userName;
        this.userEmail = userEmail;
        this.userAge = userAge;
        this.userID = userID;
    }
}
